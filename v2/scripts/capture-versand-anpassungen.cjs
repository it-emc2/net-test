// Records the card "Angebot anpassen" of today's step "Angebotsversand" (page "Zusammenfassung"):
// wording replaced, price adjusted per block, extra notes — what the card shows and what it
// stores (`offerOverrides`) — and the internal note for the team. The reference for
// apps/web/test/versand-anpassungen.test.tsx (ADR 026, phase 4). The v2 add-ons are blocked
// (with the add-on for single positions on Kosten, today's UI hides the block price adjustment
// unless the offer has one). RESUME=1 continues an interrupted run.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-versand-anpassungen.cjs   → v2/apps/web/test/fixtures/versand-anpassungen.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "versand-anpassungen.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

const TILES = { bu: "BU-Badumbau", bwt: "BWT-Badewannentür", hl: "HL-Handlauf", bl: "BL-Badelift", ah: "AH-Alltagshilfe" };
const USERS = [{ email: "capture@local.test", name: "Capture", firstName: "Cap", lastName: "Ture", hasSignature: true }];
const T = ["add", "text"], P = ["add", "price"], H = ["add", "hint"];
// on the page: ["add", "text" | "price" | "hint"] a new row · ["from" | "to", row, text] · ["amount", row, text] ·
//   ["target", row, "services" | "material"] · ["hint", row, text] · ["del", kind, row] · ["note", text] the internal note
const SCENARIOS = {
  "the card": {},
  "an empty replacement row": { acts: [T] },
  "one wording replaced": { acts: [T, ["from", 1, "Gleittür"], ["to", 1, "Flexibles Duschsystem"]] },
  "a replacement without the new wording": { acts: [T, ["from", 1, " Gleittür "]] },
  "a replacement without the old wording": { acts: [T, ["to", 1, "Flexibles Duschsystem"]] },
  "two replacements, the first removed": { acts: [T, ["from", 1, "Gleittür"], ["to", 1, "Schiebetür"], T, ["from", 2, "weiß"], ["to", 2, "Weiß matt"], ["del", "text", 1]] },
  "an empty price row": { acts: [P] },
  "work 100 € more": { acts: [P, ["amount", 1, "100"]] },
  "material 59,50 € less": { acts: [P, ["target", 1, "material"], ["amount", 1, "-59.5"]] },
  "amount typed, then emptied": { acts: [P, ["amount", 1, "100"], ["amount", 1, ""]] },
  "amount zero": { acts: [P, ["amount", 1, "0"]] },
  "two price adjustments, the first removed": { acts: [P, ["amount", 1, "100"], P, ["target", 2, "material"], ["amount", 2, "25"], ["del", "price", 1]] },
  "an empty note row": { acts: [H] },
  "one note": { acts: [H, ["hint", 1, "Die Montage erfolgt nach Absprache an einem Werktag."]] },
  "two notes, the first removed": { acts: [H, ["hint", 1, "Erster Hinweis"], H, ["hint", 2, " Zweiter Hinweis "], ["del", "hint", 1]] },
  "wording, price and two notes": { acts: [T, ["from", 1, "Gleittür"], ["to", 1, "Schiebetür"], P, ["amount", 1, "100"], H, ["hint", 1, "Erster Hinweis"], H, ["hint", 2, "Zweiter Hinweis"]] },
  "the internal note": { acts: [["note", "Kunde ist nur vormittags erreichbar."]] },
  "Badewannentür": { type: "bwt", acts: [P, ["amount", 1, "50"], H, ["hint", 1, "Hinweis"]] },
  "Alltagshilfe": { type: "ah", acts: [T, ["from", 1, "Betreuung"], ["to", 1, "Begleitung"]] },
};
const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const same = (a, b) => JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base || {}), ...Object.keys(now || {})])]
  .filter((k) => !same((base || {})[k], (now || {})[k])).map((k) => [k, k in (now || {}) ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-versand-anpassungen.cjs — do not edit", scenarios: [] };
  // RESUME=1: keep what an interrupted run already recorded (this machine crashes at random)
  const kept = [OUT + ".part", OUT].find((f) => fs.existsSync(f)); // …or add scenarios to a finished recording
  if (process.env.RESUME && kept) Object.assign(out, JSON.parse(fs.readFileSync(kept, "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, { type = "bu", acts = [] }] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/users", (r) => r.fulfill(json(USERS)));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      const alerts = [];
      page.on("dialog", (d) => { alerts.push(d.message()); d.accept().catch(() => {}); });
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator(`.tile-btn[data-step="${TILES[type]}"]`).click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
      const base = await page.evaluate(() => window.buildPayload());
      await go("Zusammenfassung");
      await page.waitForLoadState("networkidle").catch(() => {});
      await page.waitForTimeout(900);
      const viewOf = () => page.evaluate(() => {
        const txt = (n) => (n?.textContent || "").replace(/\s+/g, " ").trim();
        const vis = (n) => !!n && n.getClientRects().length > 0;
        const el = (id) => document.getElementById(id);
        const card = el("offerOverridesCard");
        const rows = (id) => [...el(id).querySelectorAll(".oo-row")].map((r) => ({ lines: [...r.querySelectorAll(".oo-line")].map((l) => { const c = l.querySelector("input, select, textarea"); return { label: txt(l.querySelector("span")), value: c.value, placeholder: c.placeholder || "", options: c.tagName === "SELECT" ? [...c.options].map((o) => ({ value: o.value, label: txt(o) })) : undefined, gross: txt(l.querySelector(".oo-gross")) || undefined }; }), remove: r.querySelector(".oo-del")?.title || "" }));
        const group = (titleEl, listId, addId) => (vis(el(addId)) ? { title: txt(titleEl), rows: rows(listId), add: txt(el(addId)) } : null);
        return {
          title: txt(card.querySelector(".oo-title")), badge: el("offerOverridesBadge").hidden ? "" : txt(el("offerOverridesBadge")), locked: !el("offerLockedMark").hidden, text: txt(card.querySelector(".oo-hint")),
          wording: group(card.querySelector(".oo-group-title"), "offerOverridesList", "offerOverridesAdd"), price: group(el("offerPriceTitle"), "offerPriceList", "offerPriceAdd"), notes: group(el("offerHinweiseTitle"), "offerHinweiseList", "offerHinweiseAdd"),
          note: { label: txt(document.querySelector('label[for="internalNote"]')), value: el("internalNote").value, placeholder: el("internalNote").placeholder, hint: txt(document.querySelector("#internalNoteCard .internal-note-hint")), max: el("internalNote").maxLength },
        };
      });
      await page.evaluate(() => { document.getElementById("offerOverridesCard").open = true; });
      const pick = (p) => ({ offerOverrides: p.offerOverrides });
      const LIST = { text: "offerOverridesList", price: "offerPriceList", hint: "offerHinweiseList" }, ADD = { text: "offerOverridesAdd", price: "offerPriceAdd", hint: "offerHinweiseAdd" };
      const offer = await page.evaluate(() => window.buildPayload());
      const entry = { name, type, offer: changed(base, offer), view: await viewOf(), acts: [] };
      for (const [kind, a, b] of acts) {
        const row = (list, n) => page.locator(`#${list} .oo-row:nth-child(${n})`);
        if (kind === "add") await page.locator(`#${ADD[a]}`).click();
        else if (kind === "from") { await row(LIST.text, a).locator("input").nth(0).fill(b); }
        else if (kind === "to") { await row(LIST.text, a).locator("input").nth(1).fill(b); }
        else if (kind === "amount") { await row(LIST.price, a).locator("input").fill(b); }
        else if (kind === "target") { await row(LIST.price, a).locator("select").selectOption(b); }
        else if (kind === "hint") { await row(LIST.hint, a).locator("textarea").fill(b); }
        else if (kind === "del") { await row(LIST[a], b).locator(".oo-del").click(); }
        else if (kind === "note") { await page.locator("#internalNote").fill(a); await page.locator("#internalNote").blur(); }
        else throw new Error(`act not handled: ${kind}`);
        await page.waitForTimeout(900);
        entry.acts.push({ act: [kind, a, b].filter((x) => x !== undefined), stored: changed(pick(offer), pick(await page.evaluate(() => window.buildPayload()))), view: await viewOf() });
      }
      await ctx.close();
      console.log(name);
      return { base, entry };
    };
    let got;
    for (let attempt = 1; !got; attempt++) {
      try { got = await record(); }
      catch (err) {
        if (attempt >= 6) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.users = USERS.map(({ email, name }) => ({ email, name }));
    out.bases = { ...(out.bases || {}), [type]: (out.bases || {})[type] || got.base };
    out.scenarios.push(got.entry);
    fs.writeFileSync(OUT + ".part", JSON.stringify(out));
  }
  await browser.close();
  out.scenarios.sort((x, y) => Object.keys(SCENARIOS).indexOf(x.name) - Object.keys(SCENARIOS).indexOf(y.name));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

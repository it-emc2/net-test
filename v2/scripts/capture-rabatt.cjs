// Records what today's UI stores and shows on the step "Aufschlag / Rabatt" for the discount
// part: the overview of the sums, the opt-in "Rabatt hinzufügen", the discount on materials
// (only for Kassenkunde with a markup of at least 50 %), the Neukundenbonus (only above the
// threshold) and the free grab bar (only with an eligible grab bar in the offer) — the reference
// for apps/web/test/rabatt.test.tsx (ADR 026, phase 4). Every price answer is recorded with the
// part of the request that decides it, so the test can replay it. The v2 add-ons are blocked.
// RESUME=1 continues an interrupted run.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-rabatt.cjs   → v2/apps/web/test/fixtures/rabatt.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "rabatt.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

const BIG = ["big"]; // enough material for a total above the Neukundenbonus threshold
const GRAB = ["grab", "1"]; // one grab bar the free-grab-bar offer applies to
const YES = ["rabatt", "ja"];
// steps (the first group sets the offer up on other steps, then the page is opened):
//        ["payer", "kk"|"sz"] · ["big"] 40 wall panels as flooring · ["grab", qty] grab bar CLPESG30 ·
//        ["auf", text] the markup · ["rabatt", "ja"|"nein"] · ["slider", percent] · ["b300"] · ["bgrab"]
const SCENARIOS = {
  "untouched": [],
  "Rabatt hinzufügen, nothing to give": [YES],
  "5 % on materials": [YES, ["slider", "5"]],
  "9 % on materials": [YES, ["slider", "9"]],
  "2,5 % on materials": [YES, ["slider", "2.5"]],
  "5 %, then Kein Rabatt": [YES, ["slider", "5"], ["rabatt", "nein"]],
  "5 %, Kein Rabatt, and on again": [YES, ["slider", "5"], ["rabatt", "nein"], YES],
  "markup 40: no discount on materials": [["auf", "40"], YES],
  "5 %, then markup 40": [YES, ["slider", "5"], ["auf", "40"]],
  "markup 60: discount on materials": [["auf", "60"], YES, ["slider", "3"]],
  "Selbstzahler: no discount on materials": [["payer", "sz"], YES],
  "above the threshold: Neukundenbonus offered": [BIG, YES],
  "Neukundenbonus": [BIG, YES, ["b300"]],
  "Neukundenbonus and 5 %": [BIG, YES, ["slider", "5"], ["b300"]],
  "Neukundenbonus on and off": [BIG, YES, ["b300"], ["b300"]],
  "Neukundenbonus, then Kein Rabatt": [BIG, YES, ["b300"], ["rabatt", "nein"]],
  "Selbstzahler with Neukundenbonus": [["payer", "sz"], BIG, YES, ["b300"]],
  "grab bar in the offer: free grab bar offered": [GRAB, YES],
  "free grab bar": [GRAB, YES, ["bgrab"]],
  "free grab bar on and off": [GRAB, YES, ["bgrab"], ["bgrab"]],
  "two grab bars, one free": [["grab", "2"], YES, ["bgrab"]],
  "everything: 5 %, Neukundenbonus, free grab bar": [BIG, GRAB, YES, ["slider", "5"], ["b300"], ["bgrab"]],
  "everything, then Kein Rabatt": [BIG, GRAB, YES, ["slider", "5"], ["b300"], ["bgrab"], ["rabatt", "nein"]],
};
/** the part of a price request that decides the answer on this page */
const keyOf = (p) => [p?.Kundendaten?.payer, p?.Kundendaten?.aufschlag, !!p?.rabatt?.rabattEnabled, Number(p?.rabatt?.materialDiscountPct) || 0, !!p?.rabatt?.bonus300, !!p?.rabatt?.bonusGrab, Number(p?.duschwanne?.wallCladdingQty) || 0, Number(p?.optional?.qty_CLPESG30) || 0].join("|");

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const same = (a, b) => JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base || {}), ...Object.keys(now || {})])]
  .filter((k) => !same((base || {})[k], (now || {})[k])).map((k) => [k, k in (now || {}) ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-rabatt.cjs — do not edit", prices: {}, scenarios: [] };
  // RESUME=1: keep what an interrupted run already recorded (this machine crashes at random)
  const kept = [OUT + ".part", OUT].find((f) => fs.existsSync(f)); // …or add scenarios to a finished recording
  if (process.env.RESUME && kept) Object.assign(out, JSON.parse(fs.readFileSync(kept, "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      let last = null;
      page.on("response", async (res) => { // every price answer, by what decides it
        if (!res.ok() || new URL(res.url()).pathname !== "/api/price" || res.request().method() !== "POST") return;
        try { const req = JSON.parse(res.request().postData() || "{}"), body = await res.json(); out.prices[keyOf(req)] = body; last = body; } catch {}
      });
      const alerts = [];
      page.on("dialog", (d) => { alerts.push(d.message()); d.accept().catch(() => {}); });
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator('.tile-btn[data-step="BU-Badumbau"]').click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      await page.evaluate(() => window.setStep("Rabatt"));
      await page.waitForTimeout(500);
      const base = await page.evaluate(() => window.buildPayload());
      const P = "#page-Rabatt";
      const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
      let next = null;
      for (const [kind, a] of steps) {
        if (kind === "payer") { await go("Kundendaten"); await page.locator(`label:has(input[name="payer"][value="${a === "sz" ? "Selbstzahler" : "Kassenkunde"}"])`).first().click(); await go("Rabatt"); }
        else if (kind === "big") { await go("Fussboden"); await page.locator("#page-Fussboden label.sec-switch:has(#fbMaster)").click(); await page.locator("#fbTabBtnWall").click(); await page.locator('#wcSupplierRow .wc-sup-btn[data-sup="hm"]').click(); await page.locator("#wallCladdingArea").fill("4,5"); await page.locator("#wallCladdingArea").blur(); await page.waitForTimeout(800); await page.locator('#wallCladdingCards .wvc-card[data-size="997"]').click(); await page.locator("#wallCladdingQtyInput").fill("40"); await page.locator("#wallCladdingQtyInput").blur(); await go("Rabatt"); }
        else if (kind === "grab") { await go("Optional"); await page.evaluate((q) => { const cb = document.getElementById("opt_CLPESG30"); if (!cb.checked) cb.click(); const f = document.getElementById("qty_CLPESG30"); f.value = q; f.dispatchEvent(new Event("input", { bubbles: true })); f.dispatchEvent(new Event("change", { bubbles: true })); }, a); await go("Rabatt"); }
        else if (kind === "auf") { await page.locator("#sonderaufschlagValue").fill(a); await page.locator("#sonderaufschlagValue").blur(); }
        else if (kind === "rabatt") await page.locator(`${P} label:has(input[name="rb-add-rabatt"][value="${a}"])`).click();
        else if (kind === "slider") await page.evaluate((v) => { const el = document.getElementById("rb-material-discount"); el.value = v; el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }, a);
        else if (kind === "b300") await page.locator(`${P} label:has(#rb-bonus-300)`).click();
        else if (kind === "bgrab") await page.locator(`${P} label:has(#rb-bonus-grab)`).click();
        else throw new Error(`step not handled: ${kind}`);
        await page.waitForTimeout(1300);
      }
      await page.waitForLoadState("networkidle").catch(() => {}); // the sums on the page come from the last price answer
      await page.waitForTimeout(900);
      if (next) await page.evaluate(() => window.setStep("Rabatt"));
      const now = await page.evaluate(() => window.buildPayload());
      const view = await page.evaluate(() => {
        const el = (id) => document.getElementById(id);
        const vis = (n) => !!n && n.getClientRects().length > 0;
        const txt = (n) => (n?.textContent || "").replace(/\s+/g, " ").trim();
        const row = (cb) => cb.closest("label");
        return {
          rows: [["rb-arbeit-label", "rb-arbeit"], ["rb-material-label", "rb-material"], ["rb-opt-label", "rb-opt"], ["rb-auf-label", "rb-auf-value"]].filter(([l]) => vis(el(l))).map(([l, v]) => [txt(el(l)), txt(el(v))]),
          net: txt(el("rb-net")), vat: txt(el("rb-vat")), total: txt(el("rb-total")),
          heading: txt(el("rb-rabatt-heading")), choice: document.querySelector('input[name="rb-add-rabatt"]:checked')?.value || "", controls: vis(el("rb-rabatt-controls")),
          empty: vis(el("rb-empty-note")) ? txt(el("rb-empty-note")) : "",
          slider: { shown: vis(el("rb-material-discount")), value: el("rb-material-discount").value, text: txt(el("rb-material-discount-val")), min: el("rb-material-discount").min, max: el("rb-material-discount").max, step: el("rb-material-discount").step },
          rabatt: vis(el("rb-rabatt")) ? txt(el("rb-rabatt")) : "", after: vis(el("rb-total-after")) ? txt(el("rb-total-after")) : "",
          b300: { shown: vis(row(el("rb-bonus-300"))), checked: el("rb-bonus-300").checked, text: txt(el("rb-bonus-300-text")) },
          bgrab: { shown: vis(row(el("rb-bonus-grab"))), checked: el("rb-bonus-grab").checked, text: txt(row(el("rb-bonus-grab"))) },
          bonusTotal: vis(el("rb-bonus-total")) ? txt(el("rb-bonus-total")) : "",
        };
      });
      view.priceKey = keyOf(now);
      await ctx.close();
      console.log(name);
      const setup = Object.fromEntries(["Kundendaten", "duschwanne", "optional"].filter((k) => !same(base[k], now[k])).map((k) => [k, sortKeys(changed(base[k] || {}, now[k] || {}))]));
      const elsewhere = Object.keys(now).filter((k) => !["rabatt", "pricingRules", "Kundendaten", "duschwanne", "optional", "Arbeitszeit", "materials"].includes(k) && !same(base[k], now[k]));
      return { name, steps, rabatt: sortKeys(changed(base.rabatt, now.rabatt)), pricingRules: sortKeys(changed(base.pricingRules || {}, now.pricingRules || {})), setup, ...(elsewhere.length ? { elsewhere: Object.fromEntries(elsewhere.map((k) => [k, sortKeys(changed(base[k] || {}, now[k] || {}))])) } : {}), view, ...(next ? { next } : {}) };
    };
    let entry;
    for (let attempt = 1; !entry; attempt++) {
      try { entry = await record(); }
      catch (err) {
        if (attempt >= 6) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.scenarios.push(entry);
    fs.writeFileSync(OUT + ".part", JSON.stringify(out));
  }
  await browser.close();
  out.scenarios.sort((x, y) => Object.keys(SCENARIOS).indexOf(x.name) - Object.keys(SCENARIOS).indexOf(y.name));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

// Records what today's UI stores and prices on the Alltagshilfe step "Finanzierung" (page-Finanzierung)
// for a set of choices — the reference for apps/web/test/ah-finanzierung.test.tsx (UX-CHANGES U-050:
// the page is redesigned, but the stored `Finanzierung` and, for a Kassenkunde, the Eigenanteil must
// stay today's for the same choices). Per scenario: a new AH offer, travel time, payer and
// „2 Personen“ set on their steps, one or two services on page-ah, then on page-Finanzierung the
// ticks clicked, the Verhinderungspflege slider set, the Umwidmung amount typed, checklist ticks
// clicked — then buildPayload().Finanzierung and computeAHGesamt() are read. The v2 add-ons are blocked.
// RESUME=1 continues an interrupted run.
//
//   bash ~/emc2-local/ah2/server.sh &            (any preview server; CAPTURE_BASE=http://localhost:<port>)
//   CAPTURE_BASE=http://localhost:3002 node v2/scripts/capture-ah-finanzierung.cjs
//     → v2/apps/web/test/fixtures/ah-finanzierung.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = process.env.OUT || path.join(__dirname, "..", "apps", "web", "test", "fixtures", "ah-finanzierung.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

// setup: ["travel", "H:MM"] · ["payer", value] · ["zwei"] (tick „2 Personen mit Pflegegrad“) ·
//        ["svc", "hnd"|"ab", rhythm, "H:MM"] — then on Finanzierung:
//        ["eb"] (click the Entlastungsbetrag tick) · ["vp", "<value>"] (slider) · ["um"] (click the
//        Umwidmung tick) · ["umBetrag", "<typed>"] · ["cl", name] (click a checklist tick)
const T = ["travel", "0:25"];
const HND = ["svc", "hnd", "Wöchentlich", "2:00"];
const SCENARIOS = {
  "Kasse: nothing changed (Entlastungsbetrag ticked as the page starts)": [T, HND],
  "Kasse: Entlastungsbetrag unticked": [T, HND, ["eb"]],
  "Kasse: Entlastungsbetrag + Verhinderungspflege 100": [T, HND, ["vp", "100"]],
  "Kasse: Verhinderungspflege 50 only": [T, HND, ["eb"], ["vp", "50"]],
  "Kasse: Verhinderungspflege slider at its maximum": [T, HND, ["vp", "201.5"]],
  "Kasse: Umwidmung 150 + Entlastungsbetrag": [T, HND, ["um"], ["umBetrag", "150"]],
  "Kasse: all three sources (VP 50, Umwidmung 80)": [T, ["svc", "ab", "Wöchentlich", "3:00"], ["vp", "50"], ["um"], ["umBetrag", "80"]],
  "Kasse: Umwidmung ticked, amount typed, unticked again": [T, HND, ["um"], ["umBetrag", "120"], ["um"]],
  "Kasse: checklist, three ticks": [T, HND, ["cl", "clEntlastungAusgeschoepft"], ["cl", "clSteuerhinweis"], ["cl", "clKostenvoranschlag"]],
  "Kasse: two persons, Entlastungsbetrag ×2": [T, ["zwei"], HND],
  "Kasse: deductions above the total (small service, VP 200)": [T, ["svc", "hnd", "Monatlich", "1:00"], ["vp", "200"]],
  "Selbstzahler: ticks stored but not deducted": [T, ["payer", "Selbstzahler"], HND, ["vp", "100"], ["cl", "clSteuerhinweis"]],
};

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();

if (require.main === module) (async () => {
  const { chromium } = require("../../node_modules/playwright");
  const browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-ah-finanzierung.cjs — do not edit", scenarios: [] };
  if (process.env.RESUME && fs.existsSync(OUT + ".part")) Object.assign(out, JSON.parse(fs.readFileSync(OUT + ".part", "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
    await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
    const page = await ctx.newPage();
    const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
    await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
    await page.route("**/api/planning/**", (r) => r.abort());
    await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
    page.on("dialog", (d) => d.accept().catch(() => {}));
    await page.goto(BASE + "/", { waitUntil: "load" });
    await page.evaluate(() => { try { localStorage.removeItem("ahServices:v1"); localStorage.removeItem("ahNote:v1"); } catch {} });
    await page.locator('.tile-btn[data-step="AH-Alltagshilfe"]').click();
    await page.waitForTimeout(1500);
    const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
    const list = (k) => (k === "hnd" ? "#ahListHaushalt" : "#ahListAlltagsbegleitung");
    const card = (k) => page.locator(`${list(k)} .ah-service-card`).first();
    const fire = (sel, value) => page.evaluate(([s, v]) => {
      const el = document.querySelector(s); if (v !== undefined) el.value = v;
      el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true }));
    }, [sel, value]);
    for (const [kind, a, b, c] of steps) {
      if (kind === "travel") { await go("Arbeitszeit"); await fire("#travelTime", a); }
      else if (kind === "payer") { await go("Kundendaten"); await page.locator(`label:has(input[name="payer"][value="${a}"])`).first().click(); }
      else if (kind === "zwei") { await go("Kundendaten"); await page.evaluate(() => { const el = document.getElementById("ahZweiPersonen"); el.checked = true; el.dispatchEvent(new Event("change", { bubbles: true })); }); }
      else if (kind === "svc") {
        await go("ah");
        await page.locator(a === "hnd" ? "#ahAddHaushaltBtn" : "#ahAddAlltagsBtn").click();
        await card(a).locator('.ah-sched-row select[data-card-field="regelmaessigkeit"]').first().selectOption(b);
        const [h, m] = c.split(":"); const row = card(a).locator(".ah-sched-row").first();
        await row.locator(".ah-dauer-h").fill(String(Number(h))); await row.locator(".ah-dauer-m").fill(String(Number(m)));
        await row.locator(".ah-dauer-m").dispatchEvent("change");
      }
      else {
        await go("Finanzierung");
        if (kind === "eb") await page.locator('label:has(#ahEntlastungsbetragNutzen)').click();
        else if (kind === "vp") await fire("#ahVerhinderungspflegeMonat", a);
        else if (kind === "um") await page.locator('label:has(#ahUmwidmungBeantragt)').click();
        else if (kind === "umBetrag") { await page.locator("#ahUmwidmungBetrag").fill(a); await page.locator("#ahUmwidmungBetrag").dispatchEvent("change"); }
        else if (kind === "cl") await page.locator(`label:has(input[name="${a}"])`).click();
        else throw new Error(`step not handled: ${kind}`);
      }
      await page.waitForTimeout(250);
    }
    await go("Finanzierung");
    await page.waitForTimeout(400);
    const got = await page.evaluate(() => {
      const p = window.buildPayload(), g = window.computeAHGesamt();
      return {
        Finanzierung: p.Finanzierung,
        ah: { ahServicesJson: p.ah?.ahServicesJson, services: p.ah?.services },
        Arbeitszeit: { travelTimeHHMM: p.Arbeitszeit?.travelTimeHHMM ?? null, ahTravelZone: p.Arbeitszeit?.ahTravelZone ?? null },
        Kundendaten: { payer: p.Kundendaten?.payer, ...(p.Kundendaten?.ahZweiPersonen ? { ahZweiPersonen: p.Kundendaten.ahZweiPersonen } : {}) },
        slider: document.getElementById("ahVerhinderungspflegeMonatOut")?.textContent ?? null,
        steuer: document.getElementById("ahSteuerabsetzBetrag")?.textContent ?? null,
        price: { gesamt: g.gesamt, eigenanteil: g.eigenanteil, allBase: g.allBase, entlastungsbetragMonat: g.entlastungsbetragMonat, verhinderungspflegeMonat: g.verhinderungspflegeMonat, umwidmungMonat: g.umwidmungMonat, steuerabsetzJahr: g.steuerabsetzJahr, isSelbstzahler: g.isSelbstzahler },
      };
    });
    out.scenarios.push({ name, steps, ...got });
    fs.writeFileSync(OUT + ".part", JSON.stringify(out, null, 1));
    console.log("recorded", name, JSON.stringify(got.Finanzierung), got.price.eigenanteil);
    await ctx.close();
  }
  await browser.close();
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
})().catch((e) => { console.error(e); process.exit(1); });

module.exports = { SCENARIOS };

// Records what today's UI stores and shows on the Arbeiten step of a Badumbau for given inputs
// (ADR 026, phase 4): the reference for apps/web/test/arbeiten.test.tsx. Inputs are REAL clicks
// and key presses — today's automatic ticking only reacts to those. The v2 add-ons are blocked.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-arbeiten.cjs   → v2/apps/web/test/fixtures/arbeiten.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "arbeiten.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

// steps: ["kind", value] chooses the Umbauart · ["task", value] clicks a task ·
//        ["wall+"] adds a dry-wall position · ["wall", row, mm] types its width · ["wall-", row] removes it ·
//        ["extra+"] adds a free task · ["extra", row, text] · ["extra-", row] · ["up", row] · ["down", row]
const SCENARIOS = {
  "nothing chosen": [],
  "Badewanne → Dusche": [["kind", "wanne_dusche"]],
  "Dusche → Dusche": [["kind", "dusche_dusche"]],
  "Badewanne → Badewanne": [["kind", "wanne_wanne"]],
  "Dusche → Badewanne": [["kind", "dusche_wanne"]],
  "Ohne Rückbau": [["kind", "ohne_rueckbau"]],
  "Badewanne → Dusche, then Dusche → Badewanne": [["kind", "wanne_dusche"], ["kind", "dusche_wanne"]],
  "Badewanne → Dusche, then Ohne Rückbau": [["kind", "wanne_dusche"], ["kind", "ohne_rueckbau"]],
  "a task unticked by hand stays off when the kind changes": [["kind", "wanne_dusche"], ["task", "install_tray"], ["kind", "dusche_dusche"]],
  "a task ticked by hand stays on when the kind changes": [["task", "remove_showertub"], ["kind", "wanne_dusche"], ["kind", "wanne_wanne"]],
  "a task ticked and unticked by hand, then a kind that wants it": [["task", "remove_tub"], ["task", "remove_tub"], ["kind", "wanne_dusche"]],
  "tasks by hand without a kind": [["task", "remove_toilet"], ["task", "install_toilet"], ["task", "remove_sink"], ["task", "close_valve"]],
  "kind and tasks from several groups": [["kind", "wanne_dusche"], ["task", "remove_enclosure"], ["task", "install_enclosure"], ["task", "replace_thermostat"], ["task", "remove_furniture"], ["task", "install_furniture"], ["task", "trockenbau_wc"]],
  "one dry-wall position": [["wall+"], ["wall", 1, "130"]],
  "two dry-wall positions, the first removed": [["wall+"], ["wall", 1, "130"], ["wall+"], ["wall", 2, "90"], ["wall-", 1]],
  "a dry-wall position without a width": [["wall+"]],
  "a dry-wall position added and removed": [["wall+"], ["wall-", 1]],
  "one free task": [["extra", 1, "Heizkörper versetzen"]],
  "two free tasks, the second moved up": [["extra", 1, "Heizkörper versetzen"], ["extra+"], ["extra", 2, "Fenster abdichten"], ["up", 2]],
  "two free tasks, the first removed": [["extra", 1, "Heizkörper versetzen"], ["extra+"], ["extra", 2, "Fenster abdichten"], ["extra-", 1]],
  "the same free task twice, and an empty row": [["extra", 1, "Silikonfuge erneuern"], ["extra+"], ["extra", 2, "Silikonfuge erneuern"], ["extra+"]],
};

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base), ...Object.keys(now)])]
  .filter((k) => k !== "computed" && JSON.stringify(base[k]) !== JSON.stringify(now[k])).map((k) => [k, k in now ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-arbeiten.cjs — do not edit", pricingRules: null, config: null, tasks: null, scenarios: [] };
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator('.tile-btn[data-step="BU-Badumbau"]').click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      await page.evaluate(() => window.setStep("Arbeiten"));
      await page.waitForTimeout(400);
      const base = await page.evaluate(() => window.buildPayload());
      // the snapshot of the business settings a new offer carries, and the settings it is taken from
      if (!out.pricingRules) {
        out.pricingRules = sortKeys(base.pricingRules);
        out.config = sortKeys(await page.evaluate(() => fetch("/admin/api/config/public").then((r) => r.json())));
      }
      // the groups are folded: open them so the tasks can be clicked like a user would
      await page.evaluate(() => document.querySelectorAll("#page-Arbeiten details").forEach((d) => { d.open = true; }));
      const extra = (row) => `#dw-extra-tasks .da-items .wt-extra-item:nth-child(${row})`;
      const wall = (row) => `#dw-trockenbau .tb-items .tb-item:nth-child(${row})`;
      for (const [kind, a, b] of steps) {
        if (kind === "kind") await page.locator(`#page-Arbeiten label.radio-pill:has(input[value="${a}"])`).click();
        else if (kind === "task") await page.locator(`#page-Arbeiten label.task-card:has(input[value="${a}"])`).click();
        else if (kind === "wall+") await page.locator("#dw-trockenbau .tb-add").click();
        else if (kind === "wall") { await page.locator(`${wall(a)} .tb-width`).fill(b); await page.locator(`${wall(a)} .tb-width`).blur(); }
        else if (kind === "wall-") await page.locator(`${wall(a)} .tb-remove`).click();
        else if (kind === "extra+") await page.locator("#dw-extra-tasks .da-add").click();
        else if (kind === "extra") { await page.locator(`${extra(a)} textarea`).fill(b); await page.locator(`${extra(a)} textarea`).blur(); }
        else if (kind === "extra-") await page.locator(`${extra(a)} .wt-extra-remove`).click();
        else if (kind === "up") await page.locator(`${extra(a)} .wt-extra-move-up`).click();
        else if (kind === "down") await page.locator(`${extra(a)} .wt-extra-move-down`).click();
        else throw new Error(`step not handled: ${kind}`);
        await page.waitForTimeout(900); // the automatic ticking follows the price update
      }
      await page.waitForTimeout(800);
      const now = await page.evaluate(() => window.buildPayload());
      const view = await page.evaluate(() => {
        const groups = [...document.querySelectorAll("#dw-worktasks .wt-group")];
        return {
          kind: document.querySelector('input[name="duschwanne[umbauart]"]:checked')?.value || "",
          ticked: [...document.querySelectorAll('input[name="duschwanne[workTasks][]"]:checked')].map((b) => b.value),
          counts: groups.map((g) => { const b = g.querySelector(".wt-group-count"); return b && !b.hidden ? b.textContent.trim() : ""; }).slice(0, 7),
          extraCount: document.getElementById("dw-extra-count").hidden ? "" : document.getElementById("dw-extra-count").textContent.trim(),
          extraRows: [...document.querySelectorAll("#dw-extra-tasks .da-items textarea")].map((t) => t.value),
          extraEmptyHint: !document.getElementById("dw-extra-empty").hidden,
          wallRows: [...document.querySelectorAll("#dw-trockenbau .tb-width")].map((t) => t.value),
          laborHours: document.getElementById("laborHours").value,
        };
      });
      if (!out.tasks) out.tasks = await page.evaluate(() => [...document.querySelectorAll("#dw-worktasks .wt-group")].slice(0, 7).map((g) => ({
        title: g.querySelector(".wt-group-title-row").firstChild.textContent.trim(),
        tasks: [...g.querySelectorAll('input[name="duschwanne[workTasks][]"]')].map((i) => {
          const card = i.closest("label");
          return { value: i.value, title: card.querySelector(".task-card__title")?.textContent.trim() || "", hint: card.querySelector(".task-card__hint")?.textContent.replace(/\s+/g, " ").trim() || "", sub: card.closest(".wt-subgroup")?.querySelector(".wt-subgroup__title, .wt-subgroup-title")?.textContent.trim() || "" };
        }),
      })));
      await ctx.close();
      console.log(name);
      return { name, steps, duschwanne: sortKeys(changed(base.duschwanne, now.duschwanne)), arbeitszeit: sortKeys(changed(base.Arbeitszeit, now.Arbeitszeit)), view };
    };
    let entry;
    for (let attempt = 1; !entry; attempt++) {
      try { entry = await record(); }
      catch (err) {
        if (attempt >= 5) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.scenarios.push(entry);
  }
  await browser.close();
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

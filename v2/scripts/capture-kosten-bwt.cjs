// Records what today's UI shows on the step "Kosten" (Kosten-Details) of a Badewannentür (slice 4): the
// sections Auszuführende Arbeiten, Enthält je Einheit, Material (grouped as in the offer
// document), Optionale Produkte and Summen — the reference for apps/web/test/kosten-bwt.test.tsx
// (ADR 026, phase 4). The page stores nothing; everything it shows comes from the price, so
// every scenario is recorded with the price answer it was drawn from. The v2 add-ons are blocked.
// RESUME=1 continues an interrupted run.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-kosten-bwt.cjs   → v2/apps/web/test/fixtures/kosten.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "kosten-bwt.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

const DOORS = { std: "bwtDoorStd", verona: "bwtDoorBudget", vario: "bwtDoorVariodoor", wien: "bwtDoorIndWien", glas: "bwtDoorIndWienGlas" };
const YES = ["rabatt", "ja"];
// steps (each sets the offer up on its own step; at the end the Kosten step is opened):
//        ["door", key] taps a door card · ["qty", key, n] · ["dim", key, Height|Width|DepthTop|DepthBottom, text] · ["grip", n, qty] grab bar ·
//        ["free", name, price, id, qty] free item · ["notask"] door task off · ["task", text] free task ·
//        ["az", duration, task] extra work time row · ["payer", "kk"|"sz"] · ["auf", text] the markup ·
//        ["rabatt", "ja"|"nein"] · ["slider", percent] · ["b300"] · ["bgrab"]
const SCENARIOS = {
  "new offer": [],
  "Selbstzahler": [["payer", "sz"]],
  "door Verona": [["door", "verona"]],
  "door Verona, quantity 2": [["door", "verona"], ["qty", "verona", "2"]],
  "door Variodoor": [["door", "vario"]],
  "door Wien with sizes": [["door", "wien"], ["dim", "wien", "Height", "32"], ["dim", "wien", "Width", "40.5"], ["dim", "wien", "DepthTop", "12"], ["dim", "wien", "DepthBottom", "15"]],
  "door Wien Glas": [["door", "glas"], ["dim", "glas", "Height", "28"]],
  "grab bar 30": [["grip", 30, "1"]],
  "grab bars 30 (2) and 60": [["grip", 30, "2"], ["grip", 60, "1"]],
  "free item": [["free", "Sonderanfertigung Glas", "799,00", "BWT-CUS-001", "1"]],
  "free item, quantity 3": [["free", "Zubehör", "49,50", "Z-1", "3"]],
  "free item without a quantity (not priced)": [["free", "Ohne Menge", "100", "O-1", ""]],
  "door task off": [["notask"]],
  "free tasks": [["task", "Alte Armatur demontieren"]],
  "extra work time": [["az", "130", "Anpassungsarbeiten"]],
  "markup 40": [["auf", "40"]],
  "discount on materials 5 %": [YES, ["slider", "5"]],
  "free grab bar": [["grip", 30, "1"], YES, ["bgrab"]],
  "everything": [["door", "wien"], ["dim", "wien", "Height", "30"], ["grip", 40, "2"], ["free", "Sonderanfertigung Glas", "799,00", "BWT-CUS-001", "2"], ["task", "Fuge erneuern"], ["az", "045", "Silikon"], ["auf", "10"], YES, ["slider", "5"]],
};
/** the part of a price request that decides the answer on this page */
const keyOf = (p) => [p?.Kundendaten?.payer, p?.Kundendaten?.aufschlag, !!p?.rabatt?.rabattEnabled, Number(p?.rabatt?.materialDiscountPct) || 0, !!p?.rabatt?.bonus300, !!p?.rabatt?.bonusGrab, Number(p?.duschwanne?.wallCladdingQty) || 0, Number(p?.optional?.qty_CLPESG30) || 0].join("|");

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const same = (a, b) => JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base || {}), ...Object.keys(now || {})])]
  .filter((k) => !same((base || {})[k], (now || {})[k])).map((k) => [k, k in (now || {}) ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-kosten-bwt.cjs — do not edit", scenarios: [] };
  // RESUME=1: keep what an interrupted run already recorded (this machine crashes at random)
  const kept = [OUT + ".part", OUT].find((f) => fs.existsSync(f)); // …or add scenarios to a finished recording
  if (process.env.RESUME && kept) Object.assign(out, JSON.parse(fs.readFileSync(kept, "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      const alerts = [];
      page.on("dialog", (d) => { alerts.push(d.message()); d.accept().catch(() => {}); });
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator('.tile-btn[data-step="BWT-Badewannentür"]').click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      await page.evaluate(() => window.setStep("Kosten"));
      await page.waitForTimeout(500);
      const base = await page.evaluate(() => window.buildPayload());
      const P = "#page-Rabatt";
      const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
      let next = null;
      for (const [kind, a, b, c, d] of steps) {
        if (["door", "qty", "dim", "grip"].includes(kind)) await go("bwt");
        if (kind === "door") await page.locator(`#page-bwt #${DOORS[a]}`).locator("xpath=ancestor::label[1]").locator(".img-wrap").click();
        else if (kind === "qty") { const i = page.locator(`#${DOORS[a]}Qty`); await i.fill(b); await i.blur(); }
        else if (kind === "dim") { const i = page.locator(`#${DOORS[a]}${b}`); await i.fill(c); await i.blur(); }
        else if (kind === "grip") { await page.locator(`#page-bwt label:has(#bwtAidsHaltegriff${a})`).locator(".img-wrap").click(); const i = page.locator(`#bwtAidsHaltegriff${a}Qty`); await i.fill(b); await i.blur(); }
        else if (kind === "free") {
          await go("bwt"); const row = page.locator("#page-bwt #bwt-extras .da-item").first();
          for (const [f, v] of [["name", a], ["price", b], ["id", c], ["qty", d]]) { const i = row.locator(`.da-${f}`); await i.scrollIntoViewIfNeeded(); await i.fill(v); await i.blur(); }
        }
        else if (kind === "notask") { await go("bwtArbeiten"); await page.locator('#page-bwtArbeiten label.task-card:has(input[value="deliver_install_bwt_door"])').click(); }
        else if (kind === "task") { await go("bwtArbeiten"); const t = page.locator("#page-bwtArbeiten #bwt-extra-tasks textarea").first(); await t.fill(a); await t.blur(); }
        else if (kind === "az") { await go("Arbeitszeit"); await page.locator(".bwt-az-add").click(); const row = page.locator("#bwtAzExtraFieldset .bwt-az-item").first(); await row.locator(".bwt-az-duration").fill(a); await row.locator(".bwt-az-duration").blur(); await row.locator(".bwt-az-task").fill(b); await row.locator(".bwt-az-task").blur(); }
        else if (kind === "payer") { await go("Kundendaten"); await page.locator(`label:has(input[name="payer"][value="${a === "sz" ? "Selbstzahler" : "Kassenkunde"}"])`).first().click(); }
        else if (["auf", "rabatt", "slider", "b300", "bgrab"].includes(kind)) {
          if ((await page.evaluate(() => location.hash)) !== "#Rabatt") { await go("Rabatt"); await page.waitForTimeout(600); }
          if (kind === "auf") { await page.locator("#sonderaufschlagValue").fill(a); await page.locator("#sonderaufschlagValue").blur(); }
          else if (kind === "rabatt") await page.locator(`${P} label:has(input[name="rb-add-rabatt"][value="${a}"])`).click();
          else if (kind === "slider") await page.evaluate((v) => { const el = document.getElementById("rb-material-discount"); el.value = v; el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }, a);
          else if (kind === "b300") await page.locator(`${P} label:has(#rb-bonus-300)`).click();
          else if (kind === "bgrab") await page.locator(`${P} label:has(#rb-bonus-grab)`).click();
        }
        else throw new Error(`step not handled: ${kind}`);
        await page.waitForTimeout(1300);
      }
      await go("Kosten");
      await page.waitForLoadState("networkidle").catch(() => {}); // the sums on the page come from the last price answer
      await page.waitForTimeout(900);
      if (next) await page.evaluate(() => window.setStep("Kosten"));
      const now = await page.evaluate(() => window.buildPayload());
      const view = await page.evaluate(() => {
        const txt = (n) => (n?.textContent || "").replace(/\s+/g, " ").trim();
        const vis = (n) => !!n && n.getClientRects().length > 0;
        const own = (n) => [...n.childNodes].filter((c) => c.nodeType === 3).map((c) => c.textContent).join("").replace(/\s+/g, " ").trim(); // the text without tags
        const sections = [...document.querySelectorAll("#costsSummary .kosten-section")].map((sec) => {
          const title = sec.querySelector(".kosten-section__title"), grid = sec.querySelector('.kosten-section__body div[style*="grid-template-columns"]');
          const cells = grid ? [...grid.children].slice(4) : [], rows = [];
          for (let k = 0; k < cells.length;) {
            if (cells[k].style.gridColumn) { rows.push({ subtitle: txt(cells[k]) }); k += 1; continue; }
            rows.push({ id: cells[k].dataset.lineId || "", label: own(cells[k]), tags: [...cells[k].querySelectorAll(".kosten-tag")].map(txt), qty: txt(cells[k + 1]), unit: txt(cells[k + 2]), total: txt(cells[k + 3]) }); k += 4;
          }
          return { num: txt(title.querySelector(".side-num")), title: own(title), head: grid ? [...grid.children].slice(0, 4).map(txt) : [], rows, empty: txt(sec.querySelector(".kosten-section__body > .muted")), footer: txt(sec.querySelector(".kosten-section__footer")), sums: [...sec.querySelectorAll(".kosten-sums > div")].map((d) => d.classList.contains("kosten-sums__note") ? { note: txt(d) } : { num: txt(d.querySelector(".side-num")), label: own(d.querySelector("span")), value: txt(d.querySelector("b")), rule: d.classList.contains("kosten-sums__rule"), total: d.classList.contains("kosten-sums__total") }) };
        });
        return { heading: txt(document.querySelector("#page-Kosten h2")), text: txt(document.getElementById("kostenDetailsDesc")), info: vis(document.getElementById("kostenDetailsToggle")), headerTotal: vis(document.getElementById("kostenHeaderTotal")) ? txt(document.getElementById("kostenHeaderTotal")) : "", sections, recompute: txt(document.getElementById("btnRecomputePrice")) };
      });
      const price = await page.evaluate(() => window.getCanonicalPricingData?.() || window.__pricing || null);
      await ctx.close();
      console.log(name);
      const stored = ["rabatt", "pricingRules", "Kundendaten", "duschwanne", "optional", "wandverkleidung", "duschabtrennung", "duschvorhang", "Arbeitszeit", "materials"];
      const untouched = Object.keys(now).filter((k) => !stored.includes(k) && !same(base[k], now[k]));
      const offer = Object.fromEntries(["bwt", "Arbeitszeit"].map((k) => [k, { ...now[k] }]));
      for (const k of ["sketch", "bwtSketchDataUrl"]) delete offer.bwt[k];
      return { name, steps, price, offer, view, ...(untouched.length ? { alsoChanged: untouched } : {}) };
    };
    let entry;
    for (let attempt = 1; !entry; attempt++) {
      try { entry = await record(); }
      catch (err) {
        if (attempt >= 6) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.scenarios.push(entry);
    fs.writeFileSync(OUT + ".part", JSON.stringify(out));
  }
  await browser.close();
  out.scenarios.sort((x, y) => Object.keys(SCENARIOS).indexOf(x.name) - Object.keys(SCENARIOS).indexOf(y.name));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

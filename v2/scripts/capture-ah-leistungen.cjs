// Records what today's UI stores and prices on the Alltagshilfe step "Leistungen" (page-ah) for a
// set of choices — the reference for apps/web/test/ah-leistungen.test.tsx (UX-CHANGES U-048: the
// page is redesigned, but the stored `ah` section and the price must stay today's for the same
// choices). Per scenario: a new AH offer, travel time and payer set on their steps, then on page-ah
// the services added, durations typed, rhythm chosen, tasks and "Gleicher Termin wie HnD" ticked,
// services removed — then buildPayload().ah and computeAHGesamt() are read. The v2 add-ons are blocked.
// RESUME=1 continues an interrupted run.
//
//   bash ~/emc2-local/ah1/server.sh &            (any preview server; CAPTURE_BASE=http://localhost:<port>)
//   node v2/scripts/capture-ah-leistungen.cjs  → v2/apps/web/test/fixtures/ah-leistungen.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = process.env.OUT || path.join(__dirname, "..", "apps", "web", "test", "fixtures", "ah-leistungen.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

// steps: ["travel", "H:MM"] travel time on Arbeitszeit · ["payer", "Selbstzahler"|"Kassenkunde"] ·
//        ["add", "hnd"|"ab"] · ["remove", "hnd"|"ab"] · ["dauer", kind, "H:MM"] · ["rh", kind, value] ·
//        ["task", kind, id] (tick / untick) · ["combined"] (tick / untick, AB card)
const T = ["travel", "0:25"];
const SCENARIOS = {
  "HnD weekly 1:30, two tasks": [T, ["add", "hnd"], ["rh", "hnd", "Wöchentlich"], ["dauer", "hnd", "1:30"], ["task", "hnd", "wohnungsreinigung"], ["task", "hnd", "einkaufen"]],
  "AB 14-tägig 2:00, two tasks": [T, ["add", "ab"], ["rh", "ab", "14-tägig"], ["dauer", "ab", "2:00"], ["task", "ab", "arzttermine"], ["task", "ab", "spaziergaenge"]],
  "both, same visit": [T, ["add", "hnd"], ["rh", "hnd", "14-tägig"], ["dauer", "hnd", "2:00"], ["add", "ab"], ["rh", "ab", "Monatlich"], ["dauer", "ab", "1:00"], ["combined"], ["task", "ab", "gesellschaft"]],
  "both, separate visits": [T, ["add", "ab"], ["rh", "ab", "alle drei Wochen"], ["dauer", "ab", "1:15"], ["add", "hnd"], ["rh", "hnd", "Wöchentlich"], ["dauer", "hnd", "0:45"]],
  "Selbstzahler HnD 14-tägig 1:00": [T, ["payer", "Selbstzahler"], ["add", "hnd"], ["rh", "hnd", "14-tägig"], ["dauer", "hnd", "1:00"], ["task", "hnd", "fensterputzen"]],
  "Selbstzahler AB monthly 3:00": [T, ["payer", "Selbstzahler"], ["add", "ab"], ["rh", "ab", "Monatlich"], ["dauer", "ab", "3:00"]],
  "HnD Vierteljährlich 4:00, tasks ticked out of order": [T, ["add", "hnd"], ["rh", "hnd", "Vierteljährlich"], ["dauer", "hnd", "4:00"], ["task", "hnd", "kochen"], ["task", "hnd", "fensterputzen"], ["task", "hnd", "haustiere"], ["task", "hnd", "kochen"]],
  "HnD added and removed, AB Jährlich 0:45": [T, ["add", "hnd"], ["rh", "hnd", "Monatlich"], ["dauer", "hnd", "1:00"], ["remove", "hnd"], ["add", "ab"], ["rh", "ab", "Jährlich"], ["dauer", "ab", "0:45"]],
  "both same visit, then HnD removed": [T, ["add", "hnd"], ["rh", "hnd", "Wöchentlich"], ["dauer", "hnd", "1:00"], ["add", "ab"], ["rh", "ab", "Wöchentlich"], ["dauer", "ab", "1:00"], ["combined"], ["remove", "hnd"]],
  "no travel time: HnD weekly 2:00": [["add", "hnd"], ["rh", "hnd", "Wöchentlich"], ["dauer", "hnd", "2:00"]],
  "Halbjährlich AB 8:00": [T, ["add", "ab"], ["rh", "ab", "Halbjährlich"], ["dauer", "ab", "8:00"], ["task", "ab", "entlastung"]],
};

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();

if (require.main === module) (async () => {
  const browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-ah-leistungen.cjs — do not edit", scenarios: [] };
  if (process.env.RESUME && fs.existsSync(OUT + ".part")) Object.assign(out, JSON.parse(fs.readFileSync(OUT + ".part", "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
    await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
    const page = await ctx.newPage();
    const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
    await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
    await page.route("**/api/planning/**", (r) => r.abort());
    await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
    page.on("dialog", (d) => d.accept().catch(() => {}));
    try { await page.evaluate(() => localStorage.clear()); } catch {}
    await page.goto(BASE + "/", { waitUntil: "load" });
    await page.evaluate(() => { try { localStorage.removeItem("ahServices:v1"); localStorage.removeItem("ahNote:v1"); } catch {} });
    await page.locator('.tile-btn[data-step="AH-Alltagshilfe"]').click();
    await page.waitForTimeout(1500);
    const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
    await go("ah");
    // page-ah: the cards of each kind
    const list = (k) => (k === "hnd" ? "#ahListHaushalt" : "#ahListAlltagsbegleitung");
    const card = (k) => page.locator(`${list(k)} .ah-service-card`).first();
    for (const [kind, a, b] of steps) {
      if (kind === "travel") { await go("Arbeitszeit"); await page.evaluate((v) => { const el = document.getElementById("travelTime"); el.value = v; el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }, a); await go("ah"); } // the field is hidden for AH; its value decides the zone
      else if (kind === "payer") { await go("Kundendaten"); await page.locator(`label:has(input[name="payer"][value="${a}"])`).first().click(); await go("ah"); }
      else if (kind === "add") await page.locator(a === "hnd" ? "#ahAddHaushaltBtn" : "#ahAddAlltagsBtn").click();
      else if (kind === "remove") await card(a).locator(".ah-sc-remove").click();
      else if (kind === "dauer") {
        const [h, m] = b.split(":");
        const row = card(a).locator(".ah-sched-row").first();
        await row.locator(".ah-dauer-h").fill(String(Number(h))); await row.locator(".ah-dauer-m").fill(String(Number(m)));
        await row.locator(".ah-dauer-m").dispatchEvent("change");
      }
      else if (kind === "rh") { await card(a).locator('.ah-sched-row select[data-card-field="regelmaessigkeit"]').first().selectOption(b); }
      else if (kind === "task") await card(a).locator(`input[data-task-id="${b}"]`).click();
      else if (kind === "combined") await card("ab").locator(".ah-combined-visit").click();
      else throw new Error(`step not handled: ${kind}`);
      await page.waitForTimeout(250);
    }
    await page.waitForTimeout(500);
    const got = await page.evaluate(() => {
      const p = window.buildPayload(), g = window.computeAHGesamt();
      return {
        ah: p.ah, Arbeitszeit: { travelTime: p.Arbeitszeit?.travelTime ?? null, travelTimeHHMM: p.Arbeitszeit?.travelTimeHHMM ?? null, ahTravelZone: p.Arbeitszeit?.ahTravelZone ?? null },
        Kundendaten: { payer: p.Kundendaten?.payer, postalCode: p.Kundendaten?.postalCode ?? "" }, Finanzierung: { ahEntlastungsbetragNutzen: p.Finanzierung?.ahEntlastungsbetragNutzen ?? null },
        zone: window.getAHZoneData?.() ?? null,
        price: { gesamt: g.gesamt, eigenanteil: g.eigenanteil, allBase: g.allBase, gesamtBase: g.gesamtBase, abGesamtBase: g.abGesamtBase, entlastungsbetragMonat: g.entlastungsbetragMonat },
      };
    });
    delete got.ah.sketch; // the drawing pad's state, not part of this page
    out.scenarios.push({ name, steps, ...got });
    fs.writeFileSync(OUT + ".part", JSON.stringify(out, null, 1));
    console.log("recorded", name, got.price.gesamt);
    await ctx.close();
  }
  await browser.close();
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
})().catch((e) => { console.error(e); process.exit(1); });

module.exports = { SCENARIOS };

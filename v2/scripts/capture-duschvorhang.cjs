// Records what today's UI stores and shows on the step "Duschvorhang": the switch, the situation
// (niche, corner, U-shape) with its side lengths, the drawing, the proposed curtain, rods and
// fittings with their quantities, and "Ihre Auswahl" — the reference for
// apps/web/test/duschvorhang.test.tsx (ADR 026, phase 4). The v2 add-ons are blocked.
// RESUME=1 continues an interrupted run. The catalogue the page loaded is part of the recording.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-duschvorhang.cjs   → v2/apps/web/test/fixtures/duschvorhang.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "duschvorhang.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

const ON = ["on"];
const N = [ON, ["leg", "a", "120"]];
const E = [ON, ["shape", "ecke"], ["leg", "a", "90"], ["leg", "b", "120"]];
// steps: ["on"] / ["off"] · ["shape", nische|ecke|u] · ["leg", a|b|c, cm] types a side length ·
//        ["item", article] taps a row (on / off) · ["qty", article, "+"|"-"] · ["type", article, n] types a quantity ·
//        ["ceiling", article] picks the length of the ceiling support · ["more"] other sizes
const SCENARIOS = {
  "switched on": [ON],
  "niche 120": [...N],
  "niche 90: the rod fits exactly": [ON, ["leg", "a", "90"]],
  "niche 200: two rods and a coupling": [ON, ["leg", "a", "200"]],
  "niche 450: two curtains": [ON, ["leg", "a", "450"]],
  "niche 89.6: rounded": [ON, ["leg", "a", "89.6"]],
  "length typed, then cleared": [...N, ["leg", "a", ""]],
  "length changed": [...N, ["leg", "a", "150"]],
  "corner without lengths": [ON, ["shape", "ecke"]],
  "corner, one side": [ON, ["shape", "ecke"], ["leg", "a", "90"]],
  "corner 90 + 120": [...E],
  "U-shape 90 + 120 + 90": [ON, ["shape", "u"], ["leg", "a", "90"], ["leg", "b", "120"], ["leg", "c", "90"]],
  "U-shape, then niche again": [ON, ["shape", "u"], ["leg", "a", "90"], ["leg", "b", "120"], ["leg", "c", "90"], ["shape", "nische"]],
  "niche, then corner": [...N, ["shape", "ecke"]],
  "curtain switched off": [...N, ["item", "HEWIDV120200W"]],
  "another curtain size": [...N, ["more"], ["item", "HEWIDV200200W"]],
  "other sizes shown": [...N, ["more"]],
  "two rods of the same length": [...N, ["qty", "DEPVS120", "+"]],
  "quantity cannot go below one": [...N, ["qty", "DEPVS120", "-"]],
  "quantity typed": [...N, ["type", "DEPVSRI", "3"]],
  "no rosettes": [...N, ["item", "DEPVSROS"]],
  "no rings, then another length": [...N, ["item", "DEPVSRI"], ["leg", "a", "150"]],
  "coupling by hand, then another length": [...N, ["item", "DEPVSK"], ["leg", "a", "150"]],
  "ceiling support on a niche": [...N, ["ceiling", "DEPDS80"]],
  "corner: ceiling support 80 cm": [...E, ["ceiling", "DEPDS80"]],
  "corner: ceiling support 80 cm, then another length": [...E, ["ceiling", "DEPDS80"], ["leg", "b", "150"]],
  "corner: no ceiling support, then another length": [...E, ["item", "DEPDS50"], ["leg", "b", "150"]],
  "corner: quantity by hand, then another length": [...E, ["qty", "DEPVSBO", "+"], ["leg", "a", "100"]],
  "complete, then switched off": [...N, ["off"]],
  "complete, off and on again": [...N, ["off"], ["on"]],
  "off, never switched on": [],
};

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const same = (a, b) => JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base || {}), ...Object.keys(now || {})])]
  .filter((k) => !same((base || {})[k], (now || {})[k])).map((k) => [k, k in (now || {}) ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-duschvorhang.cjs — do not edit", catalog: null, scenarios: [] };
  // RESUME=1: keep what an interrupted run already recorded (this machine crashes at random)
  const kept = [OUT + ".part", OUT].find((f) => fs.existsSync(f)); // …or add scenarios to a finished recording
  if (process.env.RESUME && kept) Object.assign(out, JSON.parse(fs.readFileSync(kept, "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      const alerts = [];
      page.on("dialog", (d) => { alerts.push(d.message()); d.accept().catch(() => {}); });
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator('.tile-btn[data-step="BU-Badumbau"]').click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      await page.evaluate(() => window.setStep("Duschvorhang"));
      await page.waitForTimeout(500);
      const base = await page.evaluate(() => window.buildPayload());
      const P = "#page-Duschvorhang";
      await page.locator("#vorhang-mount .vh-body").waitFor({ state: "attached" });
      if (!out.catalog) out.catalog = await page.evaluate(() => fetch("/api/vorhang/products").then((r) => r.json()));
      const row = (n) => `#wvWwRows .wv-row:nth-child(${n})`;
      let next = null;
      const item = (art) => page.locator(`#vorhang-mount .vh-item[data-art="${art}"]`);
      for (const [kind, a, b] of steps) {
        if (kind === "on" || kind === "off") await page.locator(`${P} label.sec-switch:has(#vorhangToggle)`).click();
        else if (kind === "shape") await page.locator(`#vorhang-mount .vhc-shapes button[data-shape="${a}"]`).click();
        else if (kind === "leg") { const inp = page.locator(`#vorhang-mount .vhc-row input[data-leg="${a}"]`); await inp.fill(b); await inp.blur(); }
        else if (kind === "item") await item(a).locator(".vh-item__text").click();
        else if (kind === "qty") await item(a).locator(`.ios-stepper [data-step="${b === "+" ? 1 : -1}"]`).click();
        else if (kind === "type") { const inp = item(a).locator('input[data-role="acc-qty"]'); await inp.fill(b); await inp.blur(); }
        else if (kind === "ceiling") await page.locator(`#vorhang-mount [data-ceiling="${a}"]`).click();
        else if (kind === "more") await page.locator("#vorhang-mount .vh-more").click();
        else throw new Error(`step not handled: ${kind}`);
        await page.waitForTimeout(500);
      }
      await page.waitForTimeout(900);
      if (next) await page.evaluate(() => window.setStep("Duschvorhang"));
      const now = await page.evaluate(() => window.buildPayload());
      const view = await page.evaluate(() => {
        const vis = (n) => !!n && n.getClientRects().length > 0;
        const txt = (n) => (n?.textContent || "").replace(/\s+/g, " ").trim();
        const root = document.getElementById("vorhang-mount"), all = (sel, r = root) => [...r.querySelectorAll(sel)];
        const svg = root.querySelector(".vhc-svg");
        const item = (r) => ({ art: r.dataset.art, kind: r.dataset.kind, title: txt(r.querySelector(".vh-item__text strong")), small: txt(r.querySelector(".vh-item__text small")), on: r.getAttribute("aria-pressed") === "true", qty: r.querySelector('input[data-role="acc-qty"]')?.value ?? null,
          lengths: all("[data-ceiling]", r).map((b) => `${b.getAttribute("aria-pressed") === "true" ? "*" : ""}${txt(b)}`) });
        const groups = all(".vh-products .vh-group");
        return {
          on: document.getElementById("vorhangToggle").checked, shown: vis(root.querySelector(".vh-body")),
          shape: root.querySelector('.vhc-shapes button[aria-pressed="true"]')?.dataset.shape || "",
          legs: all(".vhc-row").map((r) => ({ leg: r.dataset.leg, name: txt(r.querySelector(".vh-row__k")), value: r.querySelector("input").value, placeholder: r.querySelector("input").placeholder })),
          drawing: { label: svg?.getAttribute("aria-label") || "", empty: !!svg?.classList.contains("vhc-svg--empty"), badges: all(".vhc-badge", svg).map((b) => txt(b.querySelector(".vhc-badge-t"))), rods: all(".vhc-rod", svg).length, joints: all(".vhc-joint", svg).length, corners: all(".vhc-corner", svg).length, rosettes: all(".vhc-rosette", svg).length, walls: all(".vhc-wallp", svg).length },
          products: all(".vh-item", groups[0]).map(item), hint: txt(groups[0]?.querySelector(".vh-hint")), more: txt(root.querySelector(".vh-more")), moreOpen: root.querySelector(".vh-more")?.getAttribute("aria-expanded") === "true",
          fittings: all(".vh-item", groups[1]).map(item),
          summary: { head: txt(root.querySelector(".vh-sum-head strong")), sub: txt(root.querySelector(".vh-sum-head small")),
            lines: all(".vh-summary .vh-line:not(.vh-total)").map((l) => ({ name: txt(l.querySelector(".vh-line__name")?.childNodes[0]), art: txt(l.querySelector(".vh-line__name small")), stock: txt(l.querySelector(".dac-line-stock")), price: txt(l.querySelector(".vh-line__price")) })),
            total: txt(root.querySelector(".vh-total")) },
        };
      });
      await ctx.close();
      console.log(name);
      const elsewhere = Object.keys(now).filter((k) => k !== "duschabtrennung" && k !== "duschvorhang" && !same(base[k], now[k]));
      return { name, steps, duschabtrennung: sortKeys(changed(base.duschabtrennung, now.duschabtrennung)), duschvorhang: sortKeys(changed(base.duschvorhang || {}, now.duschvorhang || {})), ...(elsewhere.length ? { elsewhere: Object.fromEntries(elsewhere.map((k) => [k, sortKeys(changed(base[k] || {}, now[k] || {}))])) } : {}), view, ...(next ? { next } : {}) };
    };
    let entry;
    for (let attempt = 1; !entry; attempt++) {
      try { entry = await record(); }
      catch (err) {
        if (attempt >= 6) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.scenarios.push(entry);
    fs.writeFileSync(OUT + ".part", JSON.stringify(out));
  }
  await browser.close();
  out.scenarios.sort((x, y) => Object.keys(SCENARIOS).indexOf(x.name) - Object.keys(SCENARIOS).indexOf(y.name));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

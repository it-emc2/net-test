// Records the frame of today's step "Angebotsversand" (page "Zusammenfassung"): the contact person
// (Ansprechpartner), name and greeting of a two-person offer, the line that tells how the offer
// was sent, and the enclosed documents ("Mitgesendete Unterlagen") — the reference for
// apps/web/test/versand-rahmen.test.tsx (ADR 026, phase 4). The list of contact persons is a
// fixed, neutral one. The v2 add-ons are blocked. RESUME=1 continues an interrupted run.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-versand-rahmen.cjs   → v2/apps/web/test/fixtures/versand-rahmen.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "versand-rahmen.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

const TILES = { bu: "BU-Badumbau", bwt: "BWT-Badewannentür", hl: "HL-Handlauf", bl: "BL-Badelift", ah: "AH-Alltagshilfe" };
const USERS = [
  { email: "ap.eins@local.test", name: "AP Eins", firstName: "AP", lastName: "Eins", hasSignature: true },
  { email: "capture@local.test", name: "Capture", firstName: "Cap", lastName: "Ture", hasSignature: true },
  { email: "ap.drei@local.test", name: "AP Drei", firstName: "AP", lastName: "Drei", hasSignature: true },
];
const TWO = [["radio", "salutation", "Frau"], ["text", "firstName", "Erika"], ["text", "lastName", "Muster"], ["radio", "hasPflegegrad", "Ja"], ["radio", "pflegegrad", "3"], ["check", "twoPersons", "on"],
  ["text", "partnerSalutation", "Herr"], ["text", "partnerFirstName", "Max"], ["text", "partnerLastName", "Muster"]];
// set-up on Kundendaten: ["radio", name, value] · ["text", name, value] · ["check", name, "on" | "off"] ·
//   ["sent", "mail" | "post", time]
// on the page: ["ap", email] chooses the contact person · ["doc", id] ticks / unticks a document ·
//   ["name", text] · ["greet", text] · ["kd", ...step] a change on Kundendaten, then back to the page
const SCENARIOS = {
  "new offer": {},
  "another contact person": { acts: [["ap", "ap.eins@local.test"], ["ap", "ap.drei@local.test"]] },
  "documents unticked and ticked": { acts: [["doc", "abtretung"], ["doc", "barrierefrei"], ["doc", "abtretung"]] },
  "Selbstzahler": { setup: [["radio", "payer", "Selbstzahler"]], acts: [["doc", "vollmacht"]] },
  "Selbstzahler, then Kassenkunde again": { setup: [["radio", "payer", "Selbstzahler"]], acts: [["kd", "radio", "payer", "Kassenkunde"]] },
  "two persons": { setup: TWO },
  "two persons, name and greeting changed by hand": { setup: TWO, acts: [["name", "Eheleute Muster"], ["greet", "Liebe Familie Muster"], ["kd", "text", "partnerFirstName", "Moritz"]] },
  "two persons, only the name changed by hand": { setup: TWO, acts: [["name", "Eheleute Muster"], ["kd", "text", "partnerLastName", "Beispiel"]] },
  "two persons, then one person again": { setup: TWO, acts: [["kd", "check", "twoPersons", "off"]] },
  "sent by mail": { setup: [["sent", "mail", "2026-11-16T09:30:00.000Z"]] },
  "Badewannentür": { type: "bwt", acts: [["ap", "ap.eins@local.test"], ["doc", "vollmacht"]] },
  "Badewannentür, sent": { type: "bwt", setup: [["sent", "post", "2026-03-02T14:05:00.000Z"]] },
  "Handlauf": { type: "hl" },
  "Badelift": { type: "bl" },
  "Alltagshilfe": { type: "ah" },
};
const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const same = (a, b) => JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base || {}), ...Object.keys(now || {})])]
  .filter((k) => !same((base || {})[k], (now || {})[k])).map((k) => [k, k in (now || {}) ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-versand-rahmen.cjs — do not edit", scenarios: [] };
  // RESUME=1: keep what an interrupted run already recorded (this machine crashes at random)
  const kept = [OUT + ".part", OUT].find((f) => fs.existsSync(f)); // …or add scenarios to a finished recording
  if (process.env.RESUME && kept) Object.assign(out, JSON.parse(fs.readFileSync(kept, "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, { type = "bu", setup = [], acts = [] }] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/users", (r) => r.fulfill(json(USERS)));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      const alerts = [];
      page.on("dialog", (d) => { alerts.push(d.message()); d.accept().catch(() => {}); });
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator(`.tile-btn[data-step="${TILES[type]}"]`).click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
      const base = await page.evaluate(() => window.buildPayload());
      const kd = async ([kind, f, v]) => {
        if (kind === "sent") { await page.evaluate(([art, when]) => window.markAngebotVersendet(art, when), [f, v]); return; }
        const made = await page.evaluate(([k, f, v]) => {
          if (k === "check") { const box = document.querySelector(`#form-Kundendaten input[type=checkbox][name="${f}"]`); if (box.checked !== (v === "on")) box.click(); return true; }
          const el = k === "radio" ? document.querySelector(`#form-Kundendaten input[type=radio][name="${f}"][value="${v}"]`) : document.querySelector(`#form-Kundendaten [name="${f}"]`);
          if (!el) return false;
          if (k === "radio") el.checked = true; else el.value = v;
          el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true }));
          return true;
        }, [kind, f, v]);
        if (!made) throw new Error(`field not on the page: ${f}`);
        await page.waitForTimeout(80);
      };
      for (const st of setup) await kd(st);
      await page.waitForTimeout(600);
      await go("Zusammenfassung");
      await page.waitForTimeout(900);
      const viewOf = () => page.evaluate(() => {
        const txt = (n) => (n?.textContent || "").replace(/\s+/g, " ").trim();
        const vis = (n) => !!n && n.getClientRects().length > 0;
        const el = (id) => document.getElementById(id);
        const ap = el("zfAnsprechpartner"), two = el("zfTwoPersonCard"), docs = el("zfDocSelectionCard"), status = el("zfVersandStatus");
        return {
          heading: txt(el("zfPageTitle")),
          contact: { label: txt(document.querySelector('label[for="zfAnsprechpartner"]')), options: [...ap.options].map((o) => ({ value: o.value, label: txt(o) })), value: ap.value },
          two: vis(two) ? { title: txt(two.querySelector(".section-title")), text: txt(two.querySelector(".section-subtitle")), nameLabel: txt(two.querySelector('label[for="zfKundenName"]')), name: el("zfKundenName").value, greetingLabel: txt(two.querySelector('label[for="zfGreetingLine"]')), greeting: el("zfGreetingLine").value } : null,
          status: vis(status) ? txt(status) : null,
          docs: vis(docs) ? { title: txt(docs.querySelector(".section-title")), text: txt(docs.querySelector(".section-subtitle")), items: [...docs.querySelectorAll("label.doc-select-row")].map((l) => ({ id: l.querySelector("input").id.replace("docSel_", ""), label: txt(l.querySelector("span")), checked: l.querySelector("input").checked })) } : null,
        };
      });
      const pick = (p) => ({ Kundendaten: p.Kundendaten, docSelection: p.docSelection, zusammenfassung: p.zusammenfassung });
      const offer = await page.evaluate(() => window.buildPayload());
      const entry = { name, type, setup, offer: changed(base, offer), view: await viewOf(), acts: [] };
      for (const [kind, a, ...rest] of acts) {
        if (kind === "ap") await page.locator("#zfAnsprechpartner").selectOption(a);
        else if (kind === "doc") await page.locator(`#zfDocSelectionCard label.doc-select-row:has(#docSel_${a})`).click();
        else if (kind === "name") { await page.locator("#zfKundenName").fill(a); await page.locator("#zfKundenName").blur(); }
        else if (kind === "greet") { await page.locator("#zfGreetingLine").fill(a); await page.locator("#zfGreetingLine").blur(); }
        else if (kind === "kd") { await go("Kundendaten"); await kd([a, ...rest]); await page.waitForTimeout(500); await go("Zusammenfassung"); }
        else throw new Error(`act not handled: ${kind}`);
        await page.waitForTimeout(700);
        entry.acts.push({ act: [kind, a, ...rest], stored: changed(pick(offer), pick(await page.evaluate(() => window.buildPayload()))), view: await viewOf() });
      }
      await ctx.close();
      console.log(name);
      return { base, entry };
    };
    let got;
    for (let attempt = 1; !got; attempt++) {
      try { got = await record(); }
      catch (err) {
        if (attempt >= 6) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.users = USERS.map(({ email, name }) => ({ email, name }));
    out.bases = { ...(out.bases || {}), [type]: (out.bases || {})[type] || got.base };
    out.scenarios.push(got.entry);
    fs.writeFileSync(OUT + ".part", JSON.stringify(out));
  }
  await browser.close();
  out.scenarios.sort((x, y) => Object.keys(SCENARIOS).indexOf(x.name) - Object.keys(SCENARIOS).indexOf(y.name));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

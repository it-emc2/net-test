// Records what today's UI stores and shows for "Skizze und Notiz" on the Wandverkleidung step:
// the sketch pad (pen, eraser, line, ruler, undo, stroke width, colour, clear) and the note —
// the reference for apps/web/test/wv-skizze.test.tsx (ADR 026, phase 4). Real pointer input;
// positions are offsets from the canvas' top-left corner. The v2 add-ons are blocked.
// RESUME=1 continues an interrupted run. The picture itself (PNG) is not kept, only whether there is one.
//
//   bash v2/scripts/preview.sh &
//   node v2/scripts/capture-wv-skizze.cjs   → v2/apps/web/test/fixtures/wv-skizze.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("../../node_modules/playwright");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = path.join(__dirname, "..", "apps", "web", "test", "fixtures", "wv-skizze.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

const O = [["on"], ["open"]];
const S1 = ["stroke", [[40, 40], [80, 60], [120, 50]]];
// steps: ["on"] the Wandverkleidung switch · ["open"] taps "Skizze und Notiz" · ["tool", pen|eraser|line|ruler] ·
//        ["size", 2|4|7] · ["color", hex] · ["stroke", [[x, y], …]] press, move, release · ["tap", [x, y]] ·
//        ["undo"] · ["clear"] · ["note", text]
const SCENARIOS = {
  "opened, nothing drawn": [...O],
  "one stroke": [...O, S1],
  "a dot": [...O, ["stroke", [[60, 60]]]],
  "two strokes": [...O, S1, ["stroke", [[200, 100], [240, 140]]]],
  "stroke, then undone": [...O, S1, ["undo"]],
  "two strokes, the last undone": [...O, S1, ["stroke", [[200, 100], [240, 140]]], ["undo"]],
  "two strokes, then cleared": [...O, S1, ["stroke", [[200, 100], [240, 140]]], ["clear"]],
  "red, thick": [...O, ["color", "#dc2626"], ["size", 7], S1],
  "thin": [...O, ["size", 2], S1],
  "eraser over a stroke": [...O, S1, ["tool", "eraser"], ["stroke", [[70, 40], [70, 80]]]],
  "line: two taps": [...O, ["tool", "line"], ["tap", [50, 50]], ["tap", [250, 120]]],
  "line: one tap only": [...O, ["tool", "line"], ["tap", [50, 50]]],
  "line started, then the pen": [...O, ["tool", "line"], ["tap", [50, 50]], ["tool", "pen"], S1],
  "ruler: two taps": [...O, ["tool", "ruler"], ["tap", [50, 50]], ["tap", [250, 50]]],
  "two lines": [...O, ["tool", "line"], ["tap", [50, 50]], ["tap", [250, 120]], ["tap", [60, 200]], ["tap", [300, 200]]],
  "note": [...O, ["note", "Fenster links, Vorwand 20 cm"]],
  "note and stroke": [...O, S1, ["note", "Nische beachten"]],
  "stroke, Wandverkleidung switched off": [...O, S1, ["on"]],
};

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const same = (a, b) => JSON.stringify(sortKeys(a)) === JSON.stringify(sortKeys(b));
const changed = (base, now) => Object.fromEntries([...new Set([...Object.keys(base || {}), ...Object.keys(now || {})])]
  .filter((k) => !same((base || {})[k], (now || {})[k])).map((k) => [k, k in (now || {}) ? now[k] : "<removed>"]));

(async () => {
  let browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-wv-skizze.cjs — do not edit", scenarios: [] };
  // RESUME=1: keep what an interrupted run already recorded (this machine crashes at random)
  const kept = [OUT + ".part", OUT].find((f) => fs.existsSync(f)); // …or add scenarios to a finished recording
  if (process.env.RESUME && kept) Object.assign(out, JSON.parse(fs.readFileSync(kept, "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const record = async () => {
      const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
      await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
      const page = await ctx.newPage();
      const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
      await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
      await page.route("**/api/planning/**", (r) => r.abort());
      await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
      const alerts = [];
      page.on("dialog", (d) => { alerts.push(d.message()); d.accept().catch(() => {}); });
      await page.goto(BASE + "/", { waitUntil: "load" });
      await page.locator('.tile-btn[data-step="BU-Badumbau"]').click();
      await page.waitForFunction(() => location.hash === "#Kundendaten");
      await page.waitForTimeout(1200);
      await page.evaluate(() => window.setStep("Wandverkleidung"));
      await page.waitForTimeout(500);
      const base = await page.evaluate(() => window.buildPayload());
      const P = "#page-Wandverkleidung";
      const canvas = page.locator("#wvSketchDetails .project-sketch__canvas");
      const at = async ([x, y]) => { const b = await canvas.boundingBox(); return [b.x + x, b.y + y]; };
      let next = null;
      for (const [kind, a] of steps) {
        if (kind === "on") await page.locator(`${P} label.sec-switch:has(#wvEnabled)`).click();
        else if (kind === "open") { await page.locator("#wvSketchDetails > summary").click(); await page.waitForTimeout(400); await canvas.scrollIntoViewIfNeeded(); }
        else if (kind === "tool") await page.locator(`#wvSketchDetails .pad-tool[data-tool="${a}"]`).click();
        else if (kind === "size") await page.locator(`#wvSketchDetails .pad-size[data-size="${a}"]`).click();
        else if (kind === "color") await page.locator(`#wvSketchDetails .pad-color[data-color="${a}"]`).click();
        else if (kind === "undo") await page.locator("#wvSketchDetails .pad-undo").click();
        else if (kind === "clear") await page.locator("#wvSketchDetails .pad-clear").click();
        else if (kind === "note") { await page.locator("#wvNote").fill(a); await page.locator("#wvNote").blur(); }
        else if (kind === "stroke") { await canvas.scrollIntoViewIfNeeded(); const pts = []; for (const p of a) pts.push(await at(p)); await page.mouse.move(...pts[0]); await page.mouse.down(); for (const p of pts.slice(1)) await page.mouse.move(...p); await page.mouse.up(); }
        else if (kind === "tap") { await canvas.scrollIntoViewIfNeeded(); const p = await at(a); await page.mouse.move(...p); await page.mouse.down(); await page.mouse.up(); }
        else throw new Error(`step not handled: ${kind}`);
        await page.waitForTimeout(300);
      }
      await page.waitForTimeout(900);
      if (next) await page.evaluate(() => window.setStep("Wandverkleidung"));
      const now = await page.evaluate(() => window.buildPayload());
      const view = await page.evaluate(() => {
        const d = document.getElementById("wvSketchDetails"), vis = (n) => !!n && n.getClientRects().length > 0;
        const active = (sel, key) => d.querySelector(`${sel}.active`)?.dataset[key] || "";
        return { on: document.getElementById("wvEnabled").checked, shown: vis(d), open: d.open, summary: d.querySelector("summary").textContent.trim(), tool: active(".pad-tool", "tool"), size: active(".pad-size", "size"), color: active(".pad-color", "color"),
          tools: [...d.querySelectorAll(".pad-tool, .pad-undo")].map((b) => b.getAttribute("aria-label")), sizes: [...d.querySelectorAll(".pad-size")].map((b) => `${b.dataset.size}:${b.textContent.trim()}:${b.title}`), colors: [...d.querySelectorAll(".pad-color")].map((b) => `${b.dataset.color}:${b.title}`),
          title: d.querySelector(".project-sketch__title").textContent.trim(), subtitle: d.querySelector(".project-sketch__subtitle").textContent.trim(), hint: d.querySelector(".project-sketch__hint").textContent.trim(), clear: d.querySelector(".pad-clear").textContent.trim(),
          noteLabel: d.querySelector('label[for="wvNote"]').textContent.trim(), note: document.getElementById("wvNote").value, placeholder: document.getElementById("wvNote").placeholder };
      });
      // the picture is megabytes of PNG: keep only whether there is one
      const png = (o) => { for (const k of ["wvSketchDataUrl"]) if (o && typeof o[k] === "string" && o[k].startsWith("data:image/png")) o[k] = "<png>"; if (o?.sketch && typeof o.sketch.dataUrl === "string" && o.sketch.dataUrl.startsWith("data:image/png")) o.sketch = { ...o.sketch, dataUrl: "<png>" }; };
      png(now.wandverkleidung); png(base.wandverkleidung);
      await ctx.close();
      console.log(name);
      const elsewhere = Object.keys(now).filter((k) => k !== "wandverkleidung" && !same(base[k], now[k]));
      return { name, steps, wandverkleidung: sortKeys(changed(base.wandverkleidung, now.wandverkleidung)), ...(elsewhere.length ? { elsewhere: Object.fromEntries(elsewhere.map((k) => [k, sortKeys(changed(base[k] || {}, now[k] || {}))])) } : {}), view, ...(next ? { next } : {}) };
    };
    let entry;
    for (let attempt = 1; !entry; attempt++) {
      try { entry = await record(); }
      catch (err) {
        if (attempt >= 6) throw err;
        console.log(`  retry ${attempt} (${String(err.message || err).split("\n")[0]})`);
        await browser.close().catch(() => {});
        browser = await chromium.launch({ headless: true });
      }
    }
    out.scenarios.push(entry);
    fs.writeFileSync(OUT + ".part", JSON.stringify(out));
  }
  await browser.close();
  out.scenarios.sort((x, y) => Object.keys(SCENARIOS).indexOf(x.name) - Object.keys(SCENARIOS).indexOf(y.name));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
  console.log(`${out.scenarios.length} recordings → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });

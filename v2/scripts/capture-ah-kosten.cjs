// Records what today's UI shows on the Alltagshilfe step "Kosten" (the card built by
// __buildAHKostenHTML) for a set of offers — the reference for apps/web/test/ah-kosten.test.tsx
// (UX-CHANGES U-051: the page is rebuilt, but every per-service row — hours, visits, sums — must stay
// today's; for a Kassenkunde the totals too; a Selbstzahler's total differs on purpose, ADR 028).
// Per scenario: a new AH offer, travel time / payer / funding set on their steps, one or two services
// on page-ah (time rows, „Gleicher Termin wie HnD“), then page Kosten is opened and read: per service
// the table rows (Position, Menge, Einzelpreis, Gesamt), the service total, the footnote and the
// „Details“ text, the grand total „Gesamt / Monat“ — plus buildPayload() parts and computeAHGesamt().
// The v2 add-ons are blocked. RESUME=1 continues an interrupted run.
//
//   bash ~/emc2-local/ah3/server.sh &            (CAPTURE_BASE=http://localhost:3002)
//   CAPTURE_BASE=http://localhost:3002 node v2/scripts/capture-ah-kosten.cjs
//     → v2/apps/web/test/fixtures/ah-kosten.json
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const BASE = process.env.CAPTURE_BASE || "http://localhost:3001";
const OUT = process.env.OUT || path.join(__dirname, "..", "apps", "web", "test", "fixtures", "ah-kosten.json");
const SECRET = process.env.AUTH_SECRET || "dev-only-auth-secret-change-me";

// steps: ["travel", "H:MM"] · ["payer", value] · ["zwei"] · ["svc", "hnd"|"ab", rhythm, "H:MM"] ·
//        ["row", "hnd"|"ab", rhythm, "H:MM"] (a further time row) · ["combined"] (AB card tick) ·
//        ["vp", "<value>"] (Verhinderungspflege on Finanzierung)
const T = ["travel", "0:25"];
const HND = ["svc", "hnd", "Wöchentlich", "2:00"];
const AB = ["svc", "ab", "14-tägig", "1:30"];
const SCENARIOS = {
  "both services, separate visits, Kassenkunde": [T, HND, AB],
  "both services, same visit (kombiniert mit HnD)": [T, HND, ["svc", "ab", "Wöchentlich", "1:00"], ["combined"]],
  "HnD only": [T, ["svc", "hnd", "14-tägig", "2:30"]],
  "AB only": [T, ["svc", "ab", "Monatlich", "3:00"]],
  "Kassenkunde with funding (Entlastungsbetrag + Verhinderungspflege 100)": [T, HND, ["vp", "100"]],
  "Selbstzahler, both services": [T, ["payer", "Selbstzahler"], HND, AB],
  "Selbstzahler, HnD only": [T, ["payer", "Selbstzahler"], ["svc", "hnd", "Wöchentlich", "1:00"]],
  "HnD with two time rows": [T, HND, ["row", "hnd", "Monatlich", "1:30"]],
  "both, same visit, AB with two time rows": [T, HND, ["svc", "ab", "Wöchentlich", "1:00"], ["row", "ab", "14-tägig", "0:45"], ["combined"]],
  "zone 1 (travel 0:08), both services": [["travel", "0:08"], HND, AB],
  "zone 4 (travel 0:35), both services": [["travel", "0:35"], HND, AB],
  "no travel time, HnD": [["svc", "hnd", "Wöchentlich", "2:00"]],
  "two persons, Kassenkunde, rare rhythm": [T, ["zwei"], ["svc", "hnd", "Vierteljährlich", "4:00"], ["svc", "ab", "alle drei Wochen", "1:15"]],
};

const token = (() => {
  const payload = `${Date.now() + 3600e3}:capture@local.test`;
  return Buffer.from(payload).toString("base64url") + "." + crypto.createHmac("sha256", SECRET).update(payload).digest("hex");
})();

/** reads the Kosten card of today's page: texts only */
function readKosten() {
  const card = document.querySelector("#costsSummary .card");
  if (!card) return null;
  const t = (el) => (el.textContent || "").replace(/\s+/g, " ").trim();
  const sections = Array.from(card.querySelectorAll(":scope > section")).map((s) => {
    const grid = Array.from(s.querySelectorAll(":scope > div")).filter((d) => /grid-template-columns/.test(d.getAttribute("style") || ""));
    const rows = grid.map((d) => Array.from(d.children).map(t));
    const flex = Array.from(s.querySelectorAll(":scope > div")).find((d) => /padding-top:\s*12px/.test(d.getAttribute("style") || ""));
    const foot = Array.from(s.querySelectorAll(":scope > div")).find((d) => /border-top:\s*1px dashed/.test(d.getAttribute("style") || ""));
    const det = s.querySelector("[data-ah-details]");
    return {
      title: t(s.querySelector("h3")), head: rows[0], rows: rows.slice(1),
      total: flex ? Array.from(flex.children).map(t) : null,
      footnote: foot ? t(foot) : null,
      details: det ? t(det) : null,
    };
  });
  const grand = Array.from(card.querySelectorAll(":scope > div")).find((d) => /border-top:\s*2px/.test(d.getAttribute("style") || ""));
  return { sections, grand: grand ? Array.from(grand.children).map(t) : null, empty: /Noch keine Leistung konfiguriert/.test(card.textContent) };
}

if (require.main === module) (async () => {
  const { chromium } = require("../../node_modules/playwright");
  const browser = await chromium.launch({ headless: true });
  const out = { note: "generated by v2/scripts/capture-ah-kosten.cjs — do not edit", scenarios: [] };
  if (process.env.RESUME && fs.existsSync(OUT + ".part")) Object.assign(out, JSON.parse(fs.readFileSync(OUT + ".part", "utf8")));
  const have = new Set(out.scenarios.map((x) => x.name));
  for (const [name, steps] of Object.entries(SCENARIOS)) {
    if (have.has(name)) continue;
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, serviceWorkers: "block" });
    await ctx.addCookies([{ name: "net_session", value: token, url: BASE }]);
    const page = await ctx.newPage();
    const json = (body) => ({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
    await page.route("**/api/auth/me", (r) => r.fulfill(json({ user: { email: "capture@local.test", name: "Capture", role: "user" } })));
    await page.route("**/api/planning/**", (r) => r.abort());
    await page.route("**/v2/addons/**", (r) => (r.request().url().endsWith("/error-compat.js") ? r.continue() : r.abort()));
    page.on("dialog", (d) => d.accept().catch(() => {}));
    await page.goto(BASE + "/", { waitUntil: "load" });
    await page.evaluate(() => { try { localStorage.removeItem("ahServices:v1"); localStorage.removeItem("ahNote:v1"); } catch {} });
    await page.locator('.tile-btn[data-step="AH-Alltagshilfe"]').click();
    await page.waitForTimeout(1500);
    const go = async (st) => { await page.evaluate((x) => window.setStep(x), st); await page.waitForTimeout(400); };
    const list = (k) => (k === "hnd" ? "#ahListHaushalt" : "#ahListAlltagsbegleitung");
    const card = (k) => page.locator(`${list(k)} .ah-service-card`).first();
    const fire = (sel, value) => page.evaluate(([s, v]) => {
      const el = document.querySelector(s); if (v !== undefined) el.value = v;
      el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true }));
    }, [sel, value]);
    const setRow = async (k, idx, rhythm, hm) => {
      const row = card(k).locator(".ah-sched-row").nth(idx);
      await row.locator('select[data-card-field="regelmaessigkeit"]').selectOption(rhythm);
      const [h, m] = hm.split(":");
      await row.locator(".ah-dauer-h").fill(String(Number(h))); await row.locator(".ah-dauer-m").fill(String(Number(m)));
      await row.locator(".ah-dauer-m").dispatchEvent("change");
    };
    for (const [kind, a, b, c] of steps) {
      if (kind === "travel") { await go("Arbeitszeit"); await fire("#travelTime", a); }
      else if (kind === "payer") { await go("Kundendaten"); await page.locator(`label:has(input[name="payer"][value="${a}"])`).first().click(); }
      else if (kind === "zwei") { await go("Kundendaten"); await page.evaluate(() => { const el = document.getElementById("ahZweiPersonen"); el.checked = true; el.dispatchEvent(new Event("change", { bubbles: true })); }); }
      else if (kind === "svc") { await go("ah"); await page.locator(a === "hnd" ? "#ahAddHaushaltBtn" : "#ahAddAlltagsBtn").click(); await setRow(a, 0, b, c); }
      else if (kind === "row") { await go("ah"); await card(a).getByText("+ Zeitzeile hinzufügen").click(); const n = await card(a).locator(".ah-sched-row").count(); await setRow(a, n - 1, b, c); }
      else if (kind === "combined") { await go("ah"); await card("ab").locator(".ah-combined-visit").click(); }
      else if (kind === "vp") { await go("Finanzierung"); await fire("#ahVerhinderungspflegeMonat", a); }
      else throw new Error(`step not handled: ${kind}`);
      await page.waitForTimeout(250);
    }
    await go("Kosten");
    await page.waitForTimeout(500);
    const kosten = await page.evaluate(`(${readKosten.toString()})()`);
    const got = await page.evaluate(() => {
      const p = window.buildPayload(), g = window.computeAHGesamt();
      delete p.ah.sketch;
      return {
        ah: p.ah, Arbeitszeit: { travelTimeHHMM: p.Arbeitszeit?.travelTimeHHMM ?? null, ahTravelZone: p.Arbeitszeit?.ahTravelZone ?? null },
        Kundendaten: { payer: p.Kundendaten?.payer, postalCode: p.Kundendaten?.postalCode ?? "", ...(p.Kundendaten?.ahZweiPersonen ? { ahZweiPersonen: p.Kundendaten.ahZweiPersonen } : {}) },
        Finanzierung: p.Finanzierung,
        price: { gesamt: g.gesamt, eigenanteil: g.eigenanteil, allBase: g.allBase, gesamtBase: g.gesamtBase, abGesamtBase: g.abGesamtBase, totalMonatlichH: g.totalMonatlichH, totalEinsaetze: g.totalEinsaetze, abTotalMonatlichH: g.abTotalMonatlichH, abAnfahrtEinsaetze: g.abAnfahrtEinsaetze, entlastungsbetragMonat: g.entlastungsbetragMonat, verhinderungspflegeMonat: g.verhinderungspflegeMonat, steuerabsetzJahr: g.steuerabsetzJahr, isSelbstzahler: g.isSelbstzahler },
      };
    });
    out.scenarios.push({ name, steps, kosten, ...got });
    fs.writeFileSync(OUT + ".part", JSON.stringify(out, null, 1));
    console.log("recorded", name, got.price.gesamt, JSON.stringify(kosten?.sections?.map((s) => s.total)));
    await ctx.close();
  }
  await browser.close();
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  fs.rmSync(OUT + ".part", { force: true });
})().catch((e) => { console.error(e); process.exit(1); });

module.exports = { SCENARIOS };

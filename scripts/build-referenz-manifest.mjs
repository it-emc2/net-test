#!/usr/bin/env node
// Builds src/public/referenz-manifest.js from the photos under
// src/public/assets/referenz/<offer>/<vorher|nachher>/.
//
// File name convention (from the TR iPad exports):
//   <projekt>_<kategorie>_<a|b>.jpg                       (nachher)
//   <projekt>_<kategorie>_Schritt<n>_<beschreibung>.jpg   (vorher / Arbeitsschritte)
// Every full image needs a same-named copy in thumbs/ (≈600 px).
//
// Run after adding or removing photos:  node scripts/build-referenz-manifest.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASE = path.join(ROOT, "src/public/assets/referenz");
const OUT = path.join(ROOT, "src/public/referenz-manifest.js");

const CATEGORY_LABELS = {
  "Umbau-Wanne-zu-Dusche": "Wanne → Dusche",
  "Umbau-Dusche-zu-Dusche": "Dusche → Dusche",
  Badumbau: "Badumbau",
  "WC-Tausch": "WC-Tausch",
  Haltegriffe: "Haltegriffe",
  Badewannentuer: "Badewannentür",
  Geraetehaus: "Gerätehaus",
};

// File names are ASCII; put the umlauts back for display.
const WORD_FIXES = { Rueckbau: "Rückbau", Gefaelle: "Gefälle", Anschluesse: "Anschlüsse" };
const pretty = (s) =>
  s
    .split("-")
    .map((w) => WORD_FIXES[w] || w)
    .join(" ");

const KINDS = ["vorher", "nachher"];
const manifest = {};

for (const offer of fs.readdirSync(BASE).sort()) {
  const offerDir = path.join(BASE, offer);
  if (!fs.statSync(offerDir).isDirectory()) continue;
  for (const kind of KINDS) {
    const dir = path.join(offerDir, kind);
    if (!fs.existsSync(dir)) continue;
    const files = fs
      .readdirSync(dir)
      .filter((f) => f.toLowerCase().endsWith(".jpg"))
      .sort((a, b) => a.localeCompare(b, "de", { numeric: true }));
    const projects = new Map();
    for (const file of files) {
      const m = file.match(/^(\d+)_([^_]+)_(.+)\.jpg$/i);
      if (!m) throw new Error(`Unerwarteter Dateiname: ${offer}/${kind}/${file}`);
      if (!fs.existsSync(path.join(dir, "thumbs", file))) {
        throw new Error(`Thumbnail fehlt: ${offer}/${kind}/thumbs/${file}`);
      }
      const [, projekt, kategorie, rest] = m;
      const step = rest.match(/^Schritt(\d+)_(.+)$/);
      const label = step ? `${step[1]}. ${pretty(step[2])}` : `Ansicht ${rest.toUpperCase()}`;
      if (!projects.has(projekt)) {
        projects.set(projekt, {
          projekt,
          kategorie,
          kategorieLabel: CATEGORY_LABELS[kategorie] || pretty(kategorie),
          bilder: [],
        });
      }
      projects.get(projekt).bilder.push({ file, label });
    }
    if (projects.size) {
      manifest[offer] = manifest[offer] || {};
      manifest[offer][kind] = [...projects.values()];
    }
  }
}

const banner =
  "// GENERATED by scripts/build-referenz-manifest.mjs — do not edit by hand.\n" +
  "// Photos: src/public/assets/referenz/<offer>/<vorher|nachher>/(thumbs/)<file>\n";
fs.writeFileSync(OUT, `${banner}export const REFERENZ = ${JSON.stringify(manifest, null, 2)};\n`);

for (const [offer, kinds] of Object.entries(manifest)) {
  for (const [kind, projects] of Object.entries(kinds)) {
    const n = projects.reduce((s, p) => s + p.bilder.length, 0);
    console.log(`${offer.padEnd(4)} ${kind.padEnd(8)} ${String(projects.length).padStart(2)} Projekte  ${String(n).padStart(3)} Bilder`);
  }
}
